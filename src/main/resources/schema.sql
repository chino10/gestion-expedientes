-- Esquema de la base de datos según el diagrama de entidad-relación (Figura 18).
-- Las sentencias son compatibles con PostgreSQL y se ejecutan al iniciar la aplicación.

create table if not exists usuario (
    id                bigint generated by default as identity primary key,
    nombre            varchar(120) not null,
    email             varchar(160) not null unique,
    password_hash     varchar(100) not null,
    rol               varchar(20)  not null,
    activo            boolean      not null,
    intentos_fallidos integer      not null
);

create table if not exists cliente (
    id                   bigint generated by default as identity primary key,
    usuario_id           bigint       not null unique references usuario (id),
    apellido             varchar(80)  not null,
    nombre               varchar(80)  not null,
    documento_identidad  varchar(20)  not null unique,
    telefono             varchar(40)
);

create table if not exists requisito (
    id                   bigint generated by default as identity primary key,
    pais                 varchar(20)  not null,
    via                  varchar(80)  not null,
    documento            varchar(120) not null,
    persona              varchar(40)  not null,
    requiere_apostilla   boolean      not null,
    requiere_traduccion  boolean      not null,
    vigente_desde        date         not null,
    vigente_hasta        date
);

create table if not exists expediente (
    id            bigint generated by default as identity primary key,
    numero        varchar(20)  not null unique,
    cliente_id    bigint       not null references cliente (id),
    gestor_id     bigint       not null references usuario (id),
    pais          varchar(20)  not null,
    via           varchar(80)  not null,
    ascendiente   varchar(160) not null,
    estado        varchar(20)  not null,
    fecha_inicio  date         not null,
    fecha_turno   date,
    resolucion    varchar(500)
);

create table if not exists expediente_requisito (
    expediente_id bigint not null references expediente (id),
    requisito_id  bigint not null references requisito (id),
    primary key (expediente_id, requisito_id)
);

create table if not exists documento (
    id               bigint generated by default as identity primary key,
    expediente_id    bigint      not null references expediente (id),
    requisito_id     bigint      not null references requisito (id),
    estado_revision  varchar(20) not null,
    unique (expediente_id, requisito_id)
);

create table if not exists version_documento (
    id                    bigint generated by default as identity primary key,
    documento_id          bigint       not null references documento (id),
    cargado_por           bigint       not null references usuario (id),
    numero                integer      not null,
    ruta_archivo          varchar(400) not null,
    fecha_carga           timestamp    not null,
    apellido_declarado    varchar(80)  not null,
    nombre_declarado      varchar(80)  not null,
    declara_apostilla     boolean      not null,
    declara_traduccion    boolean      not null,
    resultado_validacion  varchar(1000),
    unique (documento_id, numero)
);

create table if not exists observacion (
    id                   bigint generated by default as identity primary key,
    version_documento_id bigint        not null references version_documento (id),
    gestor_id            bigint        not null references usuario (id),
    texto                varchar(1000) not null,
    fecha                timestamp     not null,
    resuelta             boolean       not null
);

create table if not exists evento_trazabilidad (
    id             bigint generated by default as identity primary key,
    expediente_id  bigint       references expediente (id),
    usuario_id     bigint       not null references usuario (id),
    accion         varchar(40)  not null,
    detalle        varchar(500) not null,
    fecha_hora     timestamp    not null
);
